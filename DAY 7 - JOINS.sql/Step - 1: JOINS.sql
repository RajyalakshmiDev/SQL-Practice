--- Def: JOIN is used to combine data from multiple tables based on a related column.

Example: 
Table 1 → Employees
emp_id	name	dept_id
Table 2 → Departments
dept_id	department_name
Then We need to know which department an employee is in so we can join them.

Types of JOINS: 1. INNER JOIN
                2. LEFT JOIN
                3. Right JOIN
                4. FULL JOIN
